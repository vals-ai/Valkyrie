        index_pages = (
            _flatten_navigation(cli_navigation)[0],
            _flatten_navigation(sdk_navigation)[0],
            _flatten_navigation(types_pages)[0],
        )
        index_routes = {f"/{page.removesuffix('/index')}" for page in index_pages}
        link_pattern = rf"\(/{re.escape(reference_root.as_posix())}/[^)]*\)"


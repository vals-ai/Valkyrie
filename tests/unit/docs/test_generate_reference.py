        rendered = generate_reference.render_reference()
        anchors_by_page = {
            path: {
                line.split("{#", 1)[1].split("}", 1)[0]
                for line in content.splitlines()
                if line.startswith("## ") and "{#" in line
            }
            for path, content in rendered.items()
            if path.suffix == ".mdx"
        }
        reference_root = Path(next(iter(rendered)).parts[0])
        guides = [path for path in sorted(_DOCS_ROOT.rglob("*.mdx")) if path.parts[1] != reference_root.name]

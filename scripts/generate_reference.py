def _clean_docstring(value: object) -> str:
    if not isinstance(value, str):
        return ""
    return inspect.cleandoc(value)


def _format_value(value: object) -> str:
    if value is None:
        return "None"
    if isinstance(value, bool):
        return "True" if value else "False"
    if isinstance(value, Enum):
        return f"{type(value).__name__}.{value.name}"
    if isinstance(value, str):
        return repr(value)
    if isinstance(value, Path):
        return repr(str(value))
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, list):
        items = typing.cast(list[object], value)
        return "[" + ", ".join(_format_value(item) for item in items) + "]"
    if isinstance(value, tuple):
        items = typing.cast(tuple[object, ...], value)
        suffix = "," if len(items) == 1 else ""
        return "(" + ", ".join(_format_value(item) for item in items) + suffix + ")"
    if isinstance(value, dict):
        items = typing.cast(dict[object, object], value)
        rendered = (f"{_format_value(key)}: {_format_value(item)}" for key, item in items.items())
        return "{" + ", ".join(rendered) + "}"
    if isinstance(value, type):
        return value.__name__
    return type(value).__name__


def _format_annotation(annotation: object) -> str:
    if annotation is inspect.Signature.empty or annotation is inspect.Parameter.empty:
        return "Any"
    if annotation is None or annotation is type(None):
        return "None"
    if isinstance(annotation, str):
        return annotation
    if isinstance(annotation, ForwardRef):
        return annotation.__forward_arg__
    if isinstance(annotation, typing.TypeVar):
        return annotation.__name__

    origin = get_origin(annotation)
    arguments = get_args(annotation)
    if origin is typing.Annotated:
        return _format_annotation(arguments[0])
    if origin is typing.Literal:
        return "Literal[" + ", ".join(_format_value(argument) for argument in arguments) + "]"
    if origin in {typing.Union, types.UnionType}:
        return " | ".join(_format_annotation(argument) for argument in arguments)
    if origin is not None:
        origin_name = getattr(origin, "__name__", str(origin).replace("typing.", ""))
        if arguments:
            return f"{origin_name}[{', '.join(_format_annotation(argument) for argument in arguments)}]"
        return origin_name

    name = getattr(annotation, "__name__", None)
    if isinstance(name, str):
        return name
    return str(annotation).replace("typing.", "")


def _sanitize_public_text(value: str) -> str:
    value = re.sub(
        r"(-s\s+ANTHROPIC_API_KEY)\s+[A-Za-z][A-Za-z0-9_-]+",
        r"\1 AnthropicApiKey",
        value,
    )
    return re.sub(r"\b([A-Za-z0-9._%+-]+)@vals\.ai\b", r"\1@example.com", value)


def _split_click_help(value: str) -> tuple[str, str | None]:
    match = re.search(r"\n\nExample:\s*(.+)$", value, flags=re.DOTALL)
    if match is None:
        return value.strip(), None
    summary = value[: match.start()].strip()
    example = "\n".join(line.strip() for line in match.group(1).strip().splitlines())
    return summary, example


def _format_click_type(parameter_type: click.ParamType) -> tuple[str, tuple[str, ...]]:
    constraints: list[str] = []
    if isinstance(parameter_type, click.Tuple):
        item_types = ", ".join(_format_click_type(item)[0] for item in parameter_type.types)
        return f"tuple[{item_types}]", ()
    if isinstance(parameter_type, click.Choice):
        raw_choices = typing.cast(Sequence[object], parameter_type.choices)
        choices = tuple(str(choice) for choice in raw_choices)
        constraints.append("one of " + ", ".join(f"`{choice}`" for choice in choices))
        if not parameter_type.case_sensitive:
            constraints.append("case-insensitive")
        return "choice", tuple(constraints)
    if isinstance(parameter_type, click.IntRange):
        if parameter_type.min is not None:
            constraints.append(f">= {parameter_type.min}")
        if parameter_type.max is not None:
            constraints.append(f"<= {parameter_type.max}")
        if parameter_type.clamp:
            constraints.append("clamped")
        return "integer", tuple(constraints)
    if isinstance(parameter_type, click.FloatRange):
        if parameter_type.min is not None:
            constraints.append(f">= {parameter_type.min}")
        if parameter_type.max is not None:
            constraints.append(f"<= {parameter_type.max}")
        if parameter_type.clamp:
            constraints.append("clamped")
        return "number", tuple(constraints)
    if isinstance(parameter_type, click.Path):
        if parameter_type.exists:
            constraints.append("must exist")
        if parameter_type.file_okay and not parameter_type.dir_okay:
            constraints.append("file")
        elif parameter_type.dir_okay and not parameter_type.file_okay:
            constraints.append("directory")
        if parameter_type.readable:
            constraints.append("readable")
        if parameter_type.writable:
            constraints.append("writable")
        return "path", tuple(constraints)

    stable_name = parameter_type.name.replace(" range", "")
    return stable_name, ()


def _is_click_unset(value: object) -> bool:
    return (
        isinstance(value, Enum)
        and type(value).__module__.startswith("click.")
        and type(value).__name__ == "Sentinel"
        and value.name == "UNSET"
    )


def _collect_click_parameter(parameter: click.Parameter) -> CLIParameterReference:
    parameter_type, type_constraints = _format_click_type(parameter.type)
    default = None if _is_click_unset(parameter.default) else _format_value(parameter.default)
    constraints = list(type_constraints)
    if parameter.nargs != 1:
        constraints.append(f"{parameter.nargs} values")
    if parameter.multiple:
        constraints.append("repeatable")

    if isinstance(parameter, click.Option):
        declarations = tuple((*parameter.opts, *parameter.secondary_opts))
        help_text = _sanitize_public_text(parameter.help or "")
        kind: Literal["argument", "option"] = "option"
    else:
        declarations = (parameter.human_readable_name.upper(),)
        help_text = ""
        kind = "argument"

    return CLIParameterReference(
        name=parameter.name or declarations[0].lower(),
        kind=kind,
        declarations=declarations,
        type_name=parameter_type,
        required=parameter.required,
        default=default,
        multiple=parameter.multiple,
        nargs=parameter.nargs,
        metavar=parameter.metavar,
        constraints=tuple(constraints),
        help=help_text,
    )


def collect_cli_commands() -> tuple[CLICommandReference, ...]:
    """Collect every registered leaf command without invoking Click callbacks."""
    from valkyrie.cli.main import cli

    commands: list[CLICommandReference] = []

    def visit(command: click.Command, path: tuple[str, ...]) -> None:
        if isinstance(command, click.Group):
            for name, child in command.commands.items():
                visit(child, (*path, name))
            return
        summary, example = _split_click_help(_sanitize_public_text(_clean_docstring(command.help)))
        commands.append(
            CLICommandReference(
                path=path,
                summary=summary,
                example=example,
                parameters=tuple(_collect_click_parameter(parameter) for parameter in command.params),
            )
        )

    visit(cli, ())
    return tuple(commands)


def _format_callable_parameter(parameter: inspect.Parameter) -> str:
    prefix = ""
    if parameter.kind is inspect.Parameter.VAR_POSITIONAL:
        prefix = "*"
    elif parameter.kind is inspect.Parameter.VAR_KEYWORD:
        prefix = "**"

    result = f"{prefix}{parameter.name}"
    if parameter.annotation is not inspect.Parameter.empty:
        result += f": {_format_annotation(parameter.annotation)}"
    if parameter.default is not inspect.Parameter.empty:
        result += f" = {_format_value(parameter.default)}"
    return result


def _format_signature(name: str, callable_object: Callable[..., object], *, drop_first: bool = True) -> str:
    signature = inspect.signature(callable_object, eval_str=False)
    parameters = list(signature.parameters.values())
    if drop_first and parameters and parameters[0].name in {"self", "cls"}:
        parameters = parameters[1:]

    rendered: list[str] = []
    keyword_marker_added = False
    for index, parameter in enumerate(parameters):
        if parameter.kind is inspect.Parameter.KEYWORD_ONLY and not keyword_marker_added:
            rendered.append("*")
            keyword_marker_added = True
        rendered.append(_format_callable_parameter(parameter))
        if parameter.kind is inspect.Parameter.VAR_POSITIONAL:
            keyword_marker_added = True
        if parameter.kind is inspect.Parameter.POSITIONAL_ONLY and (
            index + 1 == len(parameters) or parameters[index + 1].kind is not inspect.Parameter.POSITIONAL_ONLY
        ):
            rendered.append("/")

    return_type = _format_annotation(signature.return_annotation)
    async_prefix = (
        "async " if inspect.iscoroutinefunction(callable_object) or inspect.isasyncgenfunction(callable_object) else ""
    )
    one_line = f"{async_prefix}def {name}({', '.join(rendered)}) -> {return_type}"
    if len(one_line) <= 110:
        return one_line

    body = "\n".join(f"    {parameter}," for parameter in rendered)
    return f"{async_prefix}def {name}(\n{body}\n) -> {return_type}"


def _collect_method(name: str, callable_object: Callable[..., object]) -> SDKMethodReference:
    signature = inspect.signature(callable_object, eval_str=False)
    parameters = list(signature.parameters.values())
    if parameters and parameters[0].name in {"self", "cls"}:
        parameters = parameters[1:]
    parameter_references = tuple(
        SDKParameterReference(
            name=parameter.name,
            kind=parameter.kind.name,
            type_name=_format_annotation(parameter.annotation),
            required=parameter.default is inspect.Parameter.empty,
            default=(None if parameter.default is inspect.Parameter.empty else _format_value(parameter.default)),
        )
        for parameter in parameters
    )
    overloads = typing.get_overloads(callable_object)
    signature_sources = overloads or (callable_object,)

    return SDKMethodReference(
        name=name,
        description=_clean_docstring(inspect.getdoc(callable_object)),
        signatures=tuple(_format_signature(name, source) for source in signature_sources),
        parameters=parameter_references,
        return_types=tuple(
            _format_annotation(inspect.signature(source, eval_str=False).return_annotation)
            for source in signature_sources
        ),
    )


def _field_constraints(metadata: Sequence[object]) -> tuple[str, ...]:
    constraints: list[str] = []
    attributes = (
        ("gt", ">"),
        ("ge", ">="),
        ("lt", "<"),
        ("le", "<="),
        ("multiple_of", "multiple of"),
        ("min_length", "minimum length"),
        ("max_length", "maximum length"),
        ("pattern", "pattern"),
    )
    for item in metadata:
        for attribute, label in attributes:
            value = getattr(item, attribute, None)
            if value is not None:
                constraints.append(f"{label} {_format_value(value)}")
    return tuple(constraints)


def _field_default(field: Any) -> str | None:
    if field.is_required():
        return None
    if field.default_factory is not None:
        factory = field.default_factory
        if factory is list:
            return "[]"
        if factory is dict:
            return "{}"
        if factory is set:
            return "set()"
        factory_name = getattr(factory, "__name__", "generated value")
        return "generated value" if factory_name == "<lambda>" else f"{factory_name}()"
    return _format_value(field.default)


def _model_family(module: str) -> str:
    return module.rsplit(".", 1)[-1].replace("_", " ").title()


def _type_slug(name: str) -> str:
    """Return an acronym-aware, path-safe slug for one public type name."""
    separated = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1-\2", name)
    separated = re.sub(r"([a-z0-9])([A-Z])", r"\1-\2", separated)
    slug = re.sub(r"[^A-Za-z0-9]+", "-", separated).strip("-").lower()
    if not slug or slug in {".", ".."} or "/" in slug or "\\" in slug:
        raise ValueError(f"Unsafe public type slug for {name!r}: {slug!r}")
    return slug


def _collect_model(model: type[BaseModel]) -> SDKModelReference:
    fields = tuple(
        SDKFieldReference(
            name=name,
            type_name=_format_annotation(field.annotation),
            required=field.is_required(),
            default=_field_default(field),
            alias=field.alias if field.alias != name else None,
            constraints=_field_constraints(field.metadata),
            description=field.description or "",
        )
        for name, field in model.model_fields.items()
    )
    return SDKModelReference(
        name=model.__name__,
        module=model.__module__,
        family=_model_family(model.__module__),
        slug=_type_slug(model.__name__),
        description=_clean_docstring(inspect.getdoc(model)),
        fields=fields,
    )


def _collect_enum(enum_class: type[Enum]) -> SDKEnumReference:
    return SDKEnumReference(
        name=enum_class.__name__,
        module=enum_class.__module__,
        family=_model_family(enum_class.__module__),
        slug=_type_slug(enum_class.__name__),
        description=_clean_docstring(inspect.getdoc(enum_class)),
        members=tuple((member.name, _format_value(member.value)) for member in enum_class),
    )


def _validate_type_paths(entries: Sequence[SDKModelReference | SDKEnumReference]) -> None:
    """Reject duplicate names, duplicate slugs, and unsafe generated paths."""
    names: set[str] = set()
    paths: set[Path] = set()
    for entry in entries:
        if entry.name in names:
            raise ValueError(f"Duplicate public type name: {entry.name}")
        names.add(entry.name)
        path = _sdk_type_path(entry)
        if path in paths:
            raise ValueError(f"Duplicate public type path: {path}")
        paths.add(path)


def _collect_exception(exception_class: type[Exception]) -> SDKExceptionReference:
    if "__init__" not in exception_class.__dict__:
        signature = "(*args: object)"
    else:
        try:
            signature = str(inspect.signature(exception_class))
        except (TypeError, ValueError):
            signature = "(*args: object)"
    parent = exception_class.__base__.__name__ if exception_class.__base__ is not None else "Exception"
    return SDKExceptionReference(
        name=exception_class.__name__,
        parent=parent,
        description=_clean_docstring(inspect.getdoc(exception_class)),
        signature=f"{exception_class.__name__}{signature}",
    )


def _collect_constructor(client_class: type[object]) -> SDKMethodReference:
    method = _collect_method("Constructor", client_class.__init__)
    signature = _format_signature(client_class.__name__, client_class.__init__)
    signature = signature.removeprefix("def ").rsplit(" -> ", 1)[0] + f" -> {client_class.__name__}"
    return SDKMethodReference(
        name=method.name,
        description=_clean_docstring(inspect.getdoc(client_class)),
        signatures=(signature,),
        parameters=method.parameters,
        return_types=(client_class.__name__,),
    )


def _resource_methods(resource_class: type[object]) -> tuple[SDKMethodReference, ...]:
    methods: list[SDKMethodReference] = []
    for name, value in resource_class.__dict__.items():
        if name.startswith("_") or not callable(value):
            continue
        methods.append(_collect_method(name, value))
    return tuple(methods)


def collect_sdk_reference() -> SDKReference:
    """Collect the tested top-level SDK exports and public resource methods."""
    import valkyrie.sdk as sdk
    from valkyrie.sdk.client import ValkyrieClient
    from valkyrie.sdk.resources import AgentsResource, BenchmarksResource, BenchmarkServicesResource, RunsResource

    resource_classes = (
        ("RunsResource", "client.runs", RunsResource),
        ("BenchmarksResource", "client.benchmarks", BenchmarksResource),
        ("AgentsResource", "client.agents", AgentsResource),
        ("BenchmarkServicesResource", "client.services", BenchmarkServicesResource),
    )
    resources = tuple(
        SDKResourceReference(
            name=name,
            client_attribute=client_attribute,
            description=_clean_docstring(inspect.getdoc(resource_class)),
            methods=_resource_methods(resource_class),
        )
        for name, client_attribute, resource_class in resource_classes
    )

    models: list[SDKModelReference] = []
    enums: list[SDKEnumReference] = []
    exceptions: list[SDKExceptionReference] = []
    exports: list[SDKExportReference] = []
    for name in sdk.__all__:
        value = getattr(sdk, name)
        if inspect.isclass(value) and issubclass(value, Enum):
            enums.append(_collect_enum(value))
            kind = "enum"
            target = f"/{_route(_sdk_type_path(enums[-1]))}"
        elif inspect.isclass(value) and issubclass(value, BaseModel):
            models.append(_collect_model(value))
            kind = "model"
            target = f"/{_route(_sdk_type_path(models[-1]))}"
        elif inspect.isclass(value) and issubclass(value, Exception):
            exceptions.append(_collect_exception(value))
            kind = "exception"
            target = f"/reference/sdk/errors#{name.lower()}"
        elif value is ValkyrieClient:
            kind = "client"
            target = "/reference/sdk/client"
        else:
            kind = "export"
            target = "/reference/sdk/index"
        exports.append(SDKExportReference(name=name, kind=kind, target=target))

    _validate_type_paths((*models, *enums))

    client_methods = (
        _collect_constructor(ValkyrieClient),
        _collect_method("from_config", ValkyrieClient.from_config.__func__),
        _collect_method("close", ValkyrieClient.close),
    )
    return SDKReference(
        exports=tuple(exports),
        resources=resources,
        models=tuple(models),
        enums=tuple(enums),
        exceptions=tuple(exceptions),
        client_methods=client_methods,
    )


def _escape_cell(value: str) -> str:
    escaped = value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("|", "\\|")
    return escaped.replace("\n", "<br />")


def _code(value: str | None) -> str:
    return "—" if value is None else f"`{_escape_cell(value)}`"


def _frontmatter(title: str, description: str) -> list[str]:
    return [
        "---",
        f"title: {json.dumps(title)}",
        f"description: {json.dumps(description)}",
        "---",
        "",
        _GENERATED_MARKER,
        "",
    ]


def _route(path: Path) -> str:
    return path.with_suffix("").as_posix()


def _cli_command_path(command: CLICommandReference) -> Path:
    return Path("reference/cli", *command.path).with_suffix(".mdx")



@dataclass(frozen=True)
class CLIParameterReference:
    """Stable documentation data for one Click parameter."""

    name: str
    kind: Literal["argument", "option"]
    declarations: tuple[str, ...]
    type_name: str
    required: bool
    default: str | None
    multiple: bool
    nargs: int
    metavar: str | None
    constraints: tuple[str, ...]
    help: str


@dataclass(frozen=True)
class CLICommandReference:
    """Stable documentation data for one leaf Click command."""

    path: tuple[str, ...]
    summary: str
    example: str | None
    parameters: tuple[CLIParameterReference, ...]


@dataclass(frozen=True)
class SDKParameterReference:
    """Stable documentation data for one Python callable parameter."""

    name: str
    kind: str
    type_name: str
    required: bool
    default: str | None


@dataclass(frozen=True)
class SDKMethodReference:
    """Stable documentation data for one public SDK method."""

    name: str
    description: str
    signatures: tuple[str, ...]
    parameters: tuple[SDKParameterReference, ...]
    return_types: tuple[str, ...]


@dataclass(frozen=True)
class SDKResourceReference:
    """Stable documentation data for one SDK resource namespace."""

    name: str
    client_attribute: str
    description: str
    methods: tuple[SDKMethodReference, ...]


@dataclass(frozen=True)
class SDKFieldReference:
    """Stable documentation data for one public Pydantic model field."""

    name: str
    type_name: str
    required: bool
